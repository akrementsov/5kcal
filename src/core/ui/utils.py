def pad(text: str) -> str:
    """Добавляет отступ между текстом сообщения и inline-клавиатурой.

    Telegram обрезает trailing-пробелы и переносы строк, поэтому
    завершающий \n без символа после него исчезает и кнопки прижимаются
    вплотную к тексту. Символ нулевой ширины \u200b невидим, но не
    является пробелом — Telegram его сохраняет, и отступ остаётся.
    """
    return text + "\n\u200b"
